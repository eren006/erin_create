# ── 字体注册 ─────────────────────────────────────────────────
def find_font(names):
    dirs = [
        "/System/Library/Fonts", "/Library/Fonts",
        os.path.expanduser("~/Library/Fonts"),
        "/System/Library/Fonts/Supplemental",
    ]
    for name in names:
        for d in dirs:
            for ext in ("ttc", "ttf", "otf"):
                p = os.path.join(d, f"{name}.{ext}")
                if os.path.exists(p):
                    return p
    return None

