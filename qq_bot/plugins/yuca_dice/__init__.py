MAX_RELATIONSHIP_DRAW = 10

relationship_cmd = on_command("关系线")


@relationship_cmd.handle()
async def handle_relationship(event: MessageEvent, args=CommandArg()):
    text_arg = args.extract_plain_text().strip()
    count = 3
    if text_arg:
        if not text_arg.isdigit():
            await relationship_cmd.finish("格式：/关系线 [数量]，数量留空默认抽3条。")
            return
        count = int(text_arg)
    if not (1 <= count <= MAX_RELATIONSHIP_DRAW):
        await relationship_cmd.finish(f"数量超出范围，控制在1-{MAX_RELATIONSHIP_DRAW}条之内。")
        return

    picks = random.sample(RELATIONSHIP_LINES, count)
    lines = [f"关系线情报，抽取{count}条："]
    for i, (title, desc) in enumerate(picks, 1):
        lines.append(f"{i}. {title}\n{desc}")
    await relationship_cmd.finish("\n\n".join(lines))
